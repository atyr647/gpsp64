# ----- shifts ------------------------------------------------------------

def _t_shift(ins, addr, next_addr, ctx, op_c, flag_macro):
    """Generic shift: lsl/lsr/asr, with optional setflags suffix.

    Forms:
       SHIFT Rd, Rs, #imm
       SHIFT Rd, Rs            (shift Rd by Rs)
       SHIFTS Rd, Rs           (same, with flags)
    """
    setflags = ins.mnemonic.lower().endswith('s') and _fl(ctx)
    ops = ins.operands
    if len(ops) == 3:
        rd = op_reg_name(ops[0])
        rs = op_reg_name(ops[1])
        if rd is None or rs is None:
            return None
        if ops[2].type == ARM_OP_IMM:
            imm = ops[2].imm
            # Special: LSR #0 / ASR #0 in Thumb-1 mean shift-by-32.
            # Capstone normalises this to 32 already in op.imm.
            if imm == 0 and op_c == '<<':
                # LSL #0 = MOV (no flag change for C)
                if setflags:
                    return [f'{rd} = {rs};', f'SET_NZ({rd});']
                return [f'{rd} = {rs};']
            if imm == 32 and op_c == '<<':
                # Not encodable; treat as zero result.
                if setflags:
                    return [f'cf = {rs} & 1u;', f'{rd} = 0u;', f'SET_NZ({rd});']
                return [f'{rd} = 0u;']
            if op_c == '>>>':  # ASR
                expr_tmpl = '(u32)((s32){src} >> {n})'
            else:
                expr_tmpl = '({src} {op} {n})'
            if setflags:
                # Save source first — when rd == rs the assignment would
                # otherwise clobber the value the flag macro needs.
                expr = expr_tmpl.format(src='_src', op=op_c, n=imm)
                return [f'{{ u32 _src = {rs}; '
                        f'{rd} = {expr}; '
                        f'{flag_macro}({rd}, _src, {imm}); }}']
            expr = expr_tmpl.format(src=rs, op=op_c, n=imm)
            return [f'{rd} = {expr};']
        if ops[2].type == ARM_OP_REG:
            rm = op_reg_name(ops[2])
            if rm is None:
                return None
            # Variable shift: only low byte of Rm is used.
            if op_c == '>>>':
                expr = f'({rm} & 0xFFu) >= 32 ? ((s32){rs} >> 31) : ((s32){rs} >> ({rm} & 0xFFu))'
                expr = f'(u32)({expr})'
            else:
                expr = f'({rm} & 0xFFu) >= 32 ? 0u : ({rs} {op_c} ({rm} & 0xFFu))'
            if setflags:
                return [f'{rd} = ({expr});',
                        f'SET_NZ({rd});  /* note: cf approximation */']
            return [f'{rd} = ({expr});']
    if len(ops) == 2:
        rd = op_reg_name(ops[0])
        rm = op_reg_name(ops[1])
        if rd is None or rm is None:
            return None
        if op_c == '>>>':
            expr = f'({rm} & 0xFFu) >= 32 ? ((s32){rd} >> 31) : ((s32){rd} >> ({rm} & 0xFFu))'
            expr = f'(u32)({expr})'
        else:
            expr = f'({rm} & 0xFFu) >= 32 ? 0u : ({rd} {op_c} ({rm} & 0xFFu))'
        if setflags:
            return [f'{rd} = ({expr});', f'SET_NZ({rd});']
        return [f'{rd} = ({expr});']
    return None


def t_lsl(ins, addr, n, ctx): return _t_shift(ins, addr, n, ctx, '<<', 'LSL_FLAGS')
def t_lsr(ins, addr, n, ctx): return _t_shift(ins, addr, n, ctx, '>>', 'LSR_FLAGS')
def t_asr(ins, addr, n, ctx): return _t_shift(ins, addr, n, ctx, '>>>', 'ASR_FLAGS')


# ----- ALU register ops --------------------------------------------------

def _t_alu(ins, addr, next_addr, ctx, op_c, setflags_default):
    """Generic 2-operand ALU: AND/ORR/EOR/BIC. Always sets flags in Thumb-1."""
    setflags = (ins.mnemonic.lower().endswith('s') or setflags_default) and _fl(ctx)
    ops = ins.operands
    if len(ops) != 2:
        return None
    rd = op_reg_name(ops[0])
    rm = op_reg_name(ops[1])
    if rd is None or rm is None:
        return None
    if op_c == '&~':
        expr = f'({rd} & ~{rm})'
    else:
        expr = f'({rd} {op_c} {rm})'
    if setflags:
        return [f'{rd} = {expr};', f'SET_NZ({rd});']
    return [f'{rd} = {expr};']


def t_and(ins, a, n, c): return _t_alu(ins, a, n, c, '&', True)
def t_orr(ins, a, n, c): return _t_alu(ins, a, n, c, '|', True)
def t_eor(ins, a, n, c): return _t_alu(ins, a, n, c, '^', True)
def t_bic(ins, a, n, c): return _t_alu(ins, a, n, c, '&~', True)


def t_mvn(ins, addr, next_addr, ctx):
    setflags = ins.mnemonic.lower().endswith('s')
    ops = ins.operands
    if len(ops) != 2:
        return None
    rd = op_reg_name(ops[0])
    rm = op_reg_name(ops[1])
    if rd is None or rm is None:
        return None
    if setflags:
        return [f'{rd} = ~{rm};', f'SET_NZ({rd});']
    return [f'{rd} = ~{rm};']


def t_neg(ins, addr, next_addr, ctx):
    """NEG/NEGS/RSB/RSBS Rd, Rm[, #0] — Rd = 0 - Rm, sets flags."""
    ops = ins.operands
    if len(ops) < 2 or len(ops) > 3:
        return None
    rd = op_reg_name(ops[0])
    rm = op_reg_name(ops[1])
    if rd is None or rm is None:
        return None
    if len(ops) == 3:
        # RSB form: ops[2] should be #0 in Thumb-1
        if ops[2].type != ARM_OP_IMM or ops[2].imm != 0:
            return None
    return [f'{{ u32 _a=0u, _b={rm}; {rd}=_a-_b; SUB_FLAGS({rd},_a,_b); }}']


def t_mul(ins, addr, next_addr, ctx):
    setflags = ins.mnemonic.lower().endswith('s')
    ops = ins.operands
    # MUL Rd, Rm or MUL Rd, Rm, Rs
    if len(ops) == 2:
        rd = op_reg_name(ops[0])
        rm = op_reg_name(ops[1])
        if rd is None or rm is None:
            return None
        if setflags:
            return [f'{rd} = {rd} * {rm};', f'SET_NZ({rd});']
        return [f'{rd} = {rd} * {rm};']
    if len(ops) == 3:
        rd = op_reg_name(ops[0])
        rm = op_reg_name(ops[1])
        rs = op_reg_name(ops[2])
        if rd is None or rm is None or rs is None:
            return None
        if setflags:
            return [f'{rd} = {rm} * {rs};', f'SET_NZ({rd});']
        return [f'{rd} = {rm} * {rs};']
    return None


def t_cmp(ins, addr, next_addr, ctx):
    # Produces nothing but flags, so it vanishes when they are dead.
    if not _fl(ctx):
        return []
    ops = ins.operands
    if len(ops) != 2:
        return None
    a = op_reg_name(ops[0])
    if a is None:
        return None
    if ops[1].type == ARM_OP_IMM:
        b = f'0x{ops[1].imm:X}u'
    elif ops[1].type == ARM_OP_REG:
        b = op_reg_name(ops[1])
        if b is None:
            return None
    else:
        return None
    return [f'{{ u32 _a={a}, _b={b}, _d=_a-_b; SUB_FLAGS(_d,_a,_b); }}']


def t_cmn(ins, addr, next_addr, ctx):
    # Produces nothing but flags, so it vanishes when they are dead.
    if not _fl(ctx):
        return []
    ops = ins.operands
    if len(ops) != 2:
        return None
    a = op_reg_name(ops[0])
    if a is None:
        return None
    if ops[1].type == ARM_OP_REG:
        b = op_reg_name(ops[1])
    elif ops[1].type == ARM_OP_IMM:
        b = f'0x{ops[1].imm:X}u'
    else:
        return None
    if b is None:
        return None
    return [f'{{ u32 _a={a}, _b={b}, _d=_a+_b; ADD_FLAGS(_d,_a,_b); }}']


def t_tst(ins, addr, next_addr, ctx):
    # Produces nothing but flags, so it vanishes when they are dead.
    if not _fl(ctx):
        return []
    ops = ins.operands
    if len(ops) != 2:
        return None
    a = op_reg_name(ops[0])
    b = op_reg_name(ops[1])
    if a is None or b is None:
        return None
    return [f'SET_NZ({a} & {b});']


# ----- memory loads / stores --------------------------------------------

def _mem_addr(rd, mem, addr):
    """Build C expression for the effective address of a [mem] operand."""
    base, idx, disp = mem
    # PC-relative: in Thumb LDR Rd, [pc, #imm], PC is (insn+4) & ~3
    if base == 'pc':
        eff = (addr + 4) & ~3
        return f'0x{(eff + disp) & 0xFFFFFFFF:X}u'
    if idx:
        if disp:
            return f'({base} + {idx} + {disp})'
        return f'({base} + {idx})'
    if disp:
        return f'({base} + {disp}u)'
    return f'{base}'


def _t_load(ins, addr, next_addr, ctx, c_read, sign_ext_to=None):
    ops = ins.operands
    if len(ops) != 2:
        return None
    rd = op_reg_name(ops[0])
    if rd is None:
        return None
    mem = op_mem(ops[1])
    if mem is None or mem[0] is None:
        return None
    ea = _mem_addr(rd, mem, addr)
    if sign_ext_to == 16:
        return [f'{rd} = (u32)(s32)(s16){c_read}({ea});']
    if sign_ext_to == 8:
        return [f'{rd} = (u32)(s32)(s8){c_read}({ea});']
    return [f'{rd} = {c_read}({ea});']


def t_ldr(ins, a, n, c):  return _t_load(ins, a, n, c, 'aot_read32')
def t_ldrh(ins, a, n, c): return _t_load(ins, a, n, c, 'aot_read16')
def t_ldrb(ins, a, n, c): return _t_load(ins, a, n, c, 'aot_read8')
def t_ldrsh(ins, a, n, c): return _t_load(ins, a, n, c, 'aot_read16', 16)
def t_ldrsb(ins, a, n, c): return _t_load(ins, a, n, c, 'aot_read8', 8)


def _t_store(ins, addr, next_addr, ctx, c_write):
    ops = ins.operands
    if len(ops) != 2:
        return None
    rd = op_reg_name(ops[0])
    if rd is None:
        return None
    mem = op_mem(ops[1])
    if mem is None or mem[0] is None or mem[0] == 'pc':
        return None
    ea = _mem_addr(rd, mem, addr)
    return [f'{c_write}({ea}, {rd});']


def t_str(ins, a, n, c):  return _t_store(ins, a, n, c, 'aot_write32')
def t_strh(ins, a, n, c): return _t_store(ins, a, n, c, 'aot_write16')
def t_strb(ins, a, n, c): return _t_store(ins, a, n, c, 'aot_write8')


# ----- LDM / STM (small subset: post-increment Rb! with low regs) -------

def t_ldm(ins, addr, next_addr, ctx):
    ops = ins.operands
    if len(ops) < 2:
        return None
    base = op_reg_name(ops[0])
    if base is None:
        return None
    regs = []
    for op in ops[1:]:
        if op.type != ARM_OP_REG:
            return None
        nm = reg_name(op.reg)
        if nm is None:
            return None
        regs.append(nm)
    # Every address must come from the base's ORIGINAL value: if the
    # base is itself in the register list, loading it first would make
    # the remaining addresses depend on freshly-loaded data.  Writeback
    # happens before the loads so that, when the base is in the list,
    # the loaded value wins -- matching exec_thumb_block_mem().
    n = len(regs)
    lines = [f'{{ u32 __ldm_b = {base};']
    if ins.writeback or '!' in ins.op_str:
        lines.append(f'  {base} = __ldm_b + {n * 4}u;')
    for i, r in enumerate(regs):
        lines.append(f'  {r} = aot_read32(__ldm_b + {i * 4}u);')
    lines.append('}')
    return lines


def t_stm(ins, addr, next_addr, ctx):
    ops = ins.operands
    if len(ops) < 2:
        return None
    base = op_reg_name(ops[0])
    if base is None:
        return None
    regs = []
    for op in ops[1:]:
        if op.type != ARM_OP_REG:
            return None
        nm = reg_name(op.reg)
        if nm is None:
            return None
        regs.append(nm)
    # As for LDM, addresses come from the original base.  ARM7TDMI
    # stores the ORIGINAL base when the base is first in the list, and
    # the written-back value otherwise (exec_thumb_block_mem's
    # base_first / writeback_first logic).
    n = len(regs)
    writeback = bool(ins.writeback) or '!' in ins.op_str
    base_in_list = base in regs
    base_first = base_in_list and regs[0] == base
    writeback_first = writeback and not (base_in_list and base_first)
    lines = [f'{{ u32 __stm_b = {base};']
    if writeback_first:
        lines.append(f'  {base} = __stm_b + {n * 4}u;')
    for i, r in enumerate(regs):
        lines.append(f'  aot_write32(__stm_b + {i * 4}u, {r});')
    if writeback and not writeback_first:
        lines.append(f'  {base} = __stm_b + {n * 4}u;')
    lines.append('}')
    return lines


