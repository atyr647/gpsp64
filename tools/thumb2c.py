# Approximate per-instruction GBA cycle costs, used to accumulate a
# real (loop-trip-count-scaled) cycle charge instead of a flat guess
# per AOT dispatch call.  Not cycle-exact (that would require full
# waitstate-region modeling like the interpreter's ws_cyc tables), but
# close enough in magnitude and — critically — it scales with actual
# instructions executed, so a 64-iteration loop is charged ~64x a
# straight-line function of the same size instead of a flat constant
# regardless of how many times it looped.
_REG_ONLY_OPS = {
    'mov', 'movs', 'mvn', 'mvns', 'add', 'adds', 'sub', 'subs',
    'and', 'ands', 'orr', 'orrs', 'eor', 'eors', 'bic', 'bics',
    'lsl', 'lsls', 'lsr', 'lsrs', 'asr', 'asrs', 'ror', 'rors',
    'cmp', 'cmn', 'tst', 'neg', 'negs', 'nop',
}
_LOAD_OPS = {'ldr', 'ldrh', 'ldrb', 'ldrsh', 'ldrsb'}
_STORE_OPS = {'str', 'strh', 'strb'}
_BLOCK_OPS = {'push', 'pop', 'ldm', 'stm'}


def insn_cycles(ins):
    """Approximate GBA cycle cost for one executed Thumb instruction."""
    m = ins.mnemonic.lower()
    if m in _REG_ONLY_OPS:
        return 1
    if m == 'mul' or m == 'muls':
        return 3
    if m in _LOAD_OPS:
        return 3
    if m in _STORE_OPS:
        return 2
    if m in _BLOCK_OPS:
        n = 0
        for op in ins.operands:
            if op.type == ARM_OP_REG:
                n += 1
        return 1 + max(n, 1)
    if m in COND_BRANCH or m in UNCOND_BRANCH:
        return 2
    if m in ('bl', 'blx', 'bx'):
        return 3
    return 1  # unsupported/BAIL-only insns — minimal charge


ALL_FLAGS = frozenset('nzcv')

# Only conditional branches consume flags in the Thumb subset we
# translate (there is no ADC/SBC/RRX here), so these are the sole
# readers.
COND_FLAG_READS = {
    'beq': set('z'),  'bne': set('z'),
    'bcs': set('c'),  'bhs': set('c'),  'bcc': set('c'), 'blo': set('c'),
    'bmi': set('n'),  'bpl': set('n'),
    'bvs': set('v'),  'bvc': set('v'),
    'bhi': set('cz'), 'bls': set('cz'),
    'bge': set('nv'), 'blt': set('nv'),
    'bgt': set('nvz'), 'ble': set('nvz'),
}


def flags_written(ins):
    """Flags an instruction's translation materialises.  Must mirror what
    the translators below actually emit, or liveness would delete a flag
    computation something still reads."""
    m = ins.mnemonic.lower()
    if m in ('cmp', 'cmn'):
        return set(ALL_FLAGS)
    if m == 'tst':
        return set('nz')
    if m in ('adds', 'subs', 'negs', 'rsbs'):
        return set(ALL_FLAGS)
    if m in ('movs', 'mvns', 'ands', 'orrs', 'eors', 'bics', 'muls'):
        return set('nz')
    if m in ('lsls', 'lsrs', 'asrs', 'rors'):
        return set('nzc')
    return set()


def flags_read(ins):
    return set(COND_FLAG_READS.get(ins.mnemonic.lower(), ()))


def compute_flag_liveness(insns, branch_targets):
    """Decide, per instruction, whether its flag computation is observable.

    The AOT recomputes all of NZCV for nearly every instruction, but in
    straight-line ALU code those flags are almost always overwritten by
    the next flag-setting instruction without anything reading them.
    Eliminating the dead ones removes the single largest cost in the
    generated code, and shrinks it (which matters: the VR4300 has only a
    16 KB I-cache).

    Analysis is per basic block and deliberately conservative -- flags are
    assumed live at every block end, so anything reaching a branch, a BAIL
    or the interpreter keeps correct flags.  That gives up cross-block
    elimination but needs no fixed-point iteration and cannot be wrong.

    MEASURED: this is a BUILD-TIME optimisation, not a speed one.  It cuts
    the generated source by ~37% (1.14 MB -> 723 KB, roughly halving the
    compile of the slowest file), but the emitted MIPS code is unchanged:
    compiling aot_generated.c with and without the pass gives .text of
    165464 vs 165432 bytes, and ares measures 12.82 FPS either way.  GCC
    already performs this elimination -- nf/zf/cf/vf are function-local,
    so -O2 dead-store elimination sees exactly the same dataflow.  Keep
    the pass for build speed and legibility; do not expect FPS from it.
    """
    # Block starts: branch targets, and whatever follows a control transfer.
    starts = set()
    if insns:
        starts.add(insns[0].address)
    prev_ends_block = False
    for ins in insns:
        if ins.address in branch_targets or prev_ends_block:
            starts.add(ins.address)
        m = ins.mnemonic.lower()
        prev_ends_block = (m in COND_BRANCH or m in UNCOND_BRANCH
                           or m in ('bl', 'blx', 'bx', 'pop', 'mov', 'add'))

    blocks, cur = [], []
    for ins in insns:
        if ins.address in starts and cur:
            blocks.append(cur); cur = []
        cur.append(ins)
    if cur:
        blocks.append(cur)

    emit = {}
    for blk in blocks:
        live = set(ALL_FLAGS)          # conservative at block end
        for ins in reversed(blk):
            w = flags_written(ins)
            emit[ins.address] = bool(w & live)
            if w:
                live -= w
            live |= flags_read(ins)
    return emit


def _fl(ctx):
    """True if this instruction's flags are observable.

    Set THUMB2C_NO_LIVENESS=1 to force all flags to be materialised; used
    to A/B the liveness pass against a known-good baseline.
    """
    if os.environ.get('THUMB2C_NO_LIVENESS'):
        return True
    return ctx.get('emit_flags', True)


def translate_insn(ins, ctx):
    m = ins.mnemonic.lower()
    fn = TRANSLATORS.get(m)
    if fn is None:
        return None
    next_addr = ins.address + ins.size
    return fn(ins, ins.address, next_addr, ctx)


def translate_function(out, rom, md, pc, target_set):
    res, err = disasm_function(rom, md, pc)
    if err:
        # Skip entirely — don't register in dispatch table.
        out.write(f'/* SKIP 0x{pc:08X}: {err} */\n')
        return None

    insns, branch_targets = res
    insn_addrs = {ins.address for ins in insns}
    # Filter branch_targets to only those we actually emit. Anything
    # else needs a BAIL (the target is outside the AOT function).
    branch_targets = branch_targets & insn_addrs
    ctx = {
        'branch_targets': branch_targets,
        'insn_addrs': insn_addrs,
        'aot_targets': target_set,
        'continuations': set(),
    }
    # Which instructions actually need their flags materialised.
    flag_live = compute_flag_liveness(insns, branch_targets)
    skipped = []

    # Pre-pass: translate all instructions so we know the continuations.
    body_lines = []
    for ins in insns:
        if ins.address in branch_targets:
            body_lines.append(('label', f'L{ins.address:08X}:'))
        body_lines.append(('comment',
            f'/* {ins.address:08X}: {ins.mnemonic} {ins.op_str} */'))
        body_lines.append(('stmt', f'_cyc += {insn_cycles(ins)}u;'))
        ctx['emit_flags'] = flag_live.get(ins.address, True)
        lines = translate_insn(ins, ctx)
        if lines is None:
            skipped.append((ins.address, ins.mnemonic, ins.op_str))
            body_lines.append(('stmt',
                f'BAIL(0x{ins.address:08X}u); /* unsupported: '
                f'{ins.mnemonic} {ins.op_str} */'))
        else:
            for l in lines:
                body_lines.append(('stmt', l))
        # After this insn, if next addr is a continuation, mark it as
        # such so we emit an entry label (E_xxx) right at it.

    out.write(f'/* function 0x{pc:08X}: {len(insns)} insns, '
              f'{len(branch_targets)} branch targets, '
              f'{len(ctx["continuations"])} BL continuations */\n')
    out.write(f'static u32 aot_gen_{pc:08X}(u32 ep) {{\n')
    for i in range(13):
        out.write(f'    u32 r{i} = reg[{i}];\n')
    out.write('    u32 sp = reg[13];\n')
    out.write('    u32 lr = reg[14];\n')
    out.write('    u32 cf = reg[REG_C_FLAG], nf = reg[REG_N_FLAG];\n')
    out.write('    u32 zf = reg[REG_Z_FLAG], vf = reg[REG_V_FLAG];\n')
    out.write('    u32 _cyc = 0;\n')
    out.write('    (void)cf; (void)nf; (void)zf; (void)vf;\n')

    # Entry-point dispatch: jump to E_<addr> based on `ep`.
    if ctx['continuations']:
        out.write('    switch (ep) {\n')
        for c in sorted(ctx['continuations']):
            out.write(f'    case 0x{c:08X}u: goto E_{c:08X};\n')
        out.write(f'    default: break;  /* fall through to function head */\n')
        out.write('    }\n')

    # Emit body, inserting E_<addr> labels at continuation points.
    cont_set = ctx['continuations']
    # We need to know each insn's address to emit labels. Walk insns
    # alongside body_lines doesn't directly work — instead, emit labels
    # right before the comment line (which has the address embedded).
    for kind, text in body_lines:
        if kind == 'comment':
            # Extract addr from the comment "/* AAAAAAAA: ... */"
            try:
                addr_str = text.split('/* ', 1)[1].split(':', 1)[0]
                addr_int = int(addr_str, 16)
                if addr_int in cont_set:
                    out.write(f'E_{addr_int:08X}:\n')
            except (ValueError, IndexError):
                pass
            out.write(f'    {text}\n')
        elif kind == 'label':
            out.write(f'{text}\n')
        else:
            out.write(f'    {text}\n')

    out.write('    AOT_RETURN();\n')
    out.write('}\n\n')

    if skipped:
        out.write(f'/* 0x{pc:08X} BAILs ({len(skipped)}): ')
        out.write(', '.join(f'{m}@{a:08X}' for a, m, _ in skipped[:8]))
        if len(skipped) > 8:
            out.write(f', +{len(skipped)-8} more')
        out.write(' */\n\n')

    # Return list of all entry PCs that the dispatch table should
    # register for this function.
    return [pc] + sorted(ctx['continuations'])


